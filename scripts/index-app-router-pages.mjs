#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

import ts from 'typescript';

const ROOT = process.cwd();
const APP_ROOT = path.join(ROOT, 'web-src/app');
const COMPLIANCE_REPORT = path.join(
  ROOT,
  'reports/sonar/app-router-compliance.json'
);
const OUTPUT_PATH = path.join(ROOT, 'reports/app-router-page-index.md');

const tree = execFileSync(
  'tree',
  ['web-src/app', '-P', 'page.tsx', '--prune', '--noreport'],
  { cwd: ROOT, encoding: 'utf8' }
).trimEnd();

const complianceIssues = readComplianceIssues();
const pageFiles = walk(APP_ROOT)
  .filter((file) => path.basename(file) === 'page.tsx')
  .sort();

const pages = pageFiles.map(indexPage);
const counts = Object.fromEntries(
  ['migrated', 'partial', 'redirect', 'noncompliant'].map((status) => [
    status,
    pages.filter((page) => page.status === status).length,
  ])
);

const lines = [
  '# App Router page migration index',
  '',
  '> Generated by `pnpm index:app-router-pages`. Do not edit manually.',
  '',
  `Generated: ${new Date().toISOString()}`,
  '',
  '## Status definitions',
  '',
  '- `migrated`: the route owns its composition in `page.tsx` or App Router-local modules and has no compliance violations.',
  '- `partial`: the route is compliant, but its main `*Content`, `*View`, or `*Page` implementation is still imported from `web-src/legacy`.',
  '- `redirect`: the file is an intentional redirect-only route.',
  '- `noncompliant`: the Sonar/App Router compliance report contains an issue for the page.',
  '',
  '## Summary',
  '',
  '| Total | Migrated | Partial | Redirect | Noncompliant |',
  '| ---: | ---: | ---: | ---: | ---: |',
  `| ${pages.length} | ${counts.migrated} | ${counts.partial} | ${counts.redirect} | ${counts.noncompliant} |`,
  '',
  '## Tree',
  '',
  '```text',
  tree,
  '```',
  '',
  '## Page index',
  '',
  '| # | Status | Route | Source | Remaining ownership |',
  '| ---: | --- | --- | --- | --- |',
  ...pages.map(
    (page, index) =>
      `| ${index + 1} | ${statusLabel(page.status)} | \`${page.route}\` | \`${page.relativePath}\` | ${page.note || '—'} |`
  ),
  '',
];

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, `${lines.join('\n')}\n`);

// eslint-disable-next-line no-console
console.log(
  `App Router page index: ${pages.length} total, ${counts.migrated} migrated, ${counts.partial} partial, ${counts.redirect} redirects, ${counts.noncompliant} noncompliant`
);
// eslint-disable-next-line no-console
console.log(path.relative(ROOT, OUTPUT_PATH));

function indexPage(file) {
  const relativePath = toPosix(path.relative(ROOT, file));
  const sourceText = fs.readFileSync(file, 'utf8');
  const sourceFile = ts.createSourceFile(
    file,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX
  );
  const issues = complianceIssues.get(relativePath) || [];
  const legacyOwners = findLegacyOwners(sourceFile);

  if (issues.length) {
    return {
      relativePath,
      route: toRoute(file),
      status: 'noncompliant',
      note: issues.map((issue) => `\`${issue.ruleId}\``).join(', '),
    };
  }

  if (isRedirectOnly(sourceFile)) {
    return {
      relativePath,
      route: toRoute(file),
      status: 'redirect',
      note: 'Intentional App Router redirect',
    };
  }

  if (legacyOwners.length) {
    return {
      relativePath,
      route: toRoute(file),
      status: 'partial',
      note: legacyOwners
        .map(({ name, moduleName }) => `\`${name}\` from \`${moduleName}\``)
        .join('<br>'),
    };
  }

  return {
    relativePath,
    route: toRoute(file),
    status: 'migrated',
    note: '',
  };
}

function findLegacyOwners(sourceFile) {
  const owners = [];

  for (const statement of sourceFile.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    const moduleName = statement.moduleSpecifier.text;
    if (!moduleName.startsWith('@/') && !moduleName.startsWith('@@/')) {
      continue;
    }

    const clause = statement.importClause;
    if (clause?.name && isRouteOwnerName(clause.name.text)) {
      owners.push({ name: clause.name.text, moduleName });
    }
    if (clause?.namedBindings && ts.isNamedImports(clause.namedBindings)) {
      for (const element of clause.namedBindings.elements) {
        if (isRouteOwnerName(element.name.text)) {
          owners.push({ name: element.name.text, moduleName });
        }
      }
    }
  }

  return owners;
}

function isRouteOwnerName(name) {
  return /(?:Content|View|Page)$/.test(name);
}

function isRedirectOnly(sourceFile) {
  let hasRedirect = false;
  let hasJsx = false;

  visit(sourceFile);
  return hasRedirect && !hasJsx;

  function visit(node) {
    if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      node.expression.text === 'redirect'
    ) {
      hasRedirect = true;
    }
    if (ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) {
      hasJsx = true;
    }
    ts.forEachChild(node, visit);
  }
}

function toRoute(file) {
  const segments = path
    .relative(APP_ROOT, file)
    .split(path.sep)
    .slice(0, -1)
    .filter((segment) => !(segment.startsWith('(') && segment.endsWith(')')));
  return `/${segments.join('/')}`;
}

function readComplianceIssues() {
  if (!fs.existsSync(COMPLIANCE_REPORT)) return new Map();
  const report = JSON.parse(fs.readFileSync(COMPLIANCE_REPORT, 'utf8'));
  const byFile = new Map();

  for (const issue of report.issues || []) {
    const filePath = toPosix(issue.primaryLocation.filePath);
    const issues = byFile.get(filePath) || [];
    issues.push(issue);
    byFile.set(filePath, issues);
  }

  return byFile;
}

function statusLabel(status) {
  return {
    migrated: '✅ migrated',
    partial: '🟡 partial',
    redirect: '➡️ redirect',
    noncompliant: '❌ noncompliant',
  }[status];
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  });
}
